[CmdletBinding()]
param(
    [string]$SampleRoot = $(
        if ($env:PEMARA_SAMPLED_INSTRUMENT_ROOT) {
            $env:PEMARA_SAMPLED_INSTRUMENT_ROOT
        }
        else {
            'D:\PemaraAI\music-production\sampled-instruments'
        }
    )
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

function Write-DerivedPatch {
    param(
        [Parameter(Mandatory)] [string]$Source,
        [Parameter(Mandatory)] [string]$Destination,
        [Parameter(Mandatory)] [hashtable]$Replacements
    )

    $sourcePath = [IO.Path]::GetFullPath($Source)
    $destinationPath = [IO.Path]::GetFullPath($Destination)
    if (-not [IO.File]::Exists($sourcePath)) {
        throw "Patch de origem nao encontrado: $sourcePath"
    }
    if ([StringComparer]::OrdinalIgnoreCase.Equals($sourcePath, $destinationPath)) {
        throw 'O patch derivado nunca pode sobrescrever o patch original.'
    }

    $content = [IO.File]::ReadAllText($sourcePath)
    foreach ($entry in $Replacements.GetEnumerator()) {
        $old = [string]$entry.Key
        $new = [string]$entry.Value
        $count = ([regex]::Matches($content, [regex]::Escape($old))).Count
        if ($count -lt 1) {
            throw "Marcador esperado ausente em ${sourcePath}: $old"
        }
        $content = $content.Replace($old, $new)
    }

    $header = "// PEMARA derived patch. Original preserved. Generated by prepare_sampled_patches.ps1.`r`n"
    [IO.File]::WriteAllText(
        $destinationPath,
        $header + $content,
        [Text.UTF8Encoding]::new($false)
    )
    return Get-Item -LiteralPath $destinationPath
}

$resolvedRoot = [IO.Path]::GetFullPath($SampleRoot)
$vpoStrings = Join-Path $resolvedRoot 'libraries\Virtual-Playing-Orchestra3\Strings'
$smPrograms = Join-Path $resolvedRoot 'libraries\SMDrums-Sforzando-1.2\Programs'

$violin = Write-DerivedPatch `
    -Source (Join-Path $vpoStrings '1st-violin-SOLO-normal-mod-wheel.sfz') `
    -Destination (Join-Path $vpoStrings 'Pemara-1st-violin-SOLO-tight-tuning.sfz') `
    -Replacements @{
        'pitch_random=12' = 'pitch_random=0'
        'amp_random=1.5' = 'amp_random=0.5'
        'delay_random=0.012' = 'delay_random=0.003'
    }

$cello = Write-DerivedPatch `
    -Source (Join-Path $vpoStrings 'cello-SOLO-normal-mod-wheel.sfz') `
    -Destination (Join-Path $vpoStrings 'Pemara-cello-SOLO-tight-tuning.sfz') `
    -Replacements @{
        'pitch_random=12' = 'pitch_random=0'
        'amp_random=1.5' = 'amp_random=0.5'
        'delay_random=0.012' = 'delay_random=0.003'
    }

$drums = Write-DerivedPatch `
    -Source (Join-Path $smPrograms 'SM_Drums_kit.sfz') `
    -Destination (Join-Path $smPrograms 'Pemara_SM_Drums_GM.sfz') `
    -Replacements @{
        '#define $HHFOOTOPKEY 49' = '#define $HHFOOTOPKEY 59'
        '#define $CR13KEY 54' = '#define $CR13KEY 49'
    }

$result = [ordered]@{
    schema = 'pemara.sampled-patches.v1'
    sampleRoot = $resolvedRoot
    originalsPreserved = $true
    patches = @(
        [ordered]@{
            instrument = 'violin'
            path = $violin.FullName
            sha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath $violin.FullName).Hash.ToLowerInvariant()
            pitchRandomCents = 0
        },
        [ordered]@{
            instrument = 'cello'
            path = $cello.FullName
            sha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath $cello.FullName).Hash.ToLowerInvariant()
            pitchRandomCents = 0
        },
        [ordered]@{
            instrument = 'drums'
            path = $drums.FullName
            sha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath $drums.FullName).Hash.ToLowerInvariant()
            gmCrash49MappedToSample = $true
        }
    )
}

$result | ConvertTo-Json -Depth 5
